import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const sandbox={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync('public/trip-budget.js','utf8'),sandbox);
const B=sandbox.module.exports;
const p=(id,category,price,label='일반 성인',note='')=>({id,name:id,category,priceInfo:{price,label,note,source:'https://example.com/prices',checked:'2026-10-06'}});
const food=p('food','food','12,000원','정식'),cafe=p('cafe','cafe','5,000원','아메리카노'),museum=p('museum','culture','3,000원'),free=p('free','outdoors','무료');
const places=[food,cafe,museum,free],lookup=id=>places.find(p=>p.id===id);
const route={rows:places.map(p=>({placeId:p.id,mode:'walk'})),endWalk:{mode:'bus',steps:[{type:'BUS'},{type:'BUS'}]},walkMeters:2000};
const original=JSON.stringify(route),model=B.routeItems(route,lookup),s={enabled:true,people:2,total:50000,busFare:1500};
let e=B.estimate(model,s);
assert.equal(e.sum,46000);assert.equal(e.status,'within');assert.equal(e.remaining,4000);assert.equal(e.breakdown.transport.sum,6000);
assert.equal(JSON.stringify(route),original,'cost estimation must not mutate route');
e=B.estimate(model,{...s,total:45000});assert.equal(e.status,'over');
e=B.estimate(model,{...s,busFare:null});assert.equal(e.status,'unknown');assert.equal(e.sum,40000);assert.equal(e.unknown,1);
e=B.estimate(model,{...s,busFare:null,total:20000});assert.equal(e.status,'over','known subtotal alone can exceed cap');
e=B.estimate(model,{...s,total:null});assert.equal(e.status,'unset');
assert.equal(B.price(p('x','food','100,000원','민어코스(2인)')).unit,null);
assert.equal(B.price(p('x','food','150,000원','3~4인')).unit,null);
assert.equal(B.price(p('x','food','27,000원','한우 110g')).unit,null);
assert.equal(B.price(p('x','culture','3,000원','성인','통합 관람권')).unit,null);
assert.equal(B.price(p('x','culture','3,000원 / 2,000원','성인 / 어린이')).unit,null);
assert.equal(B.price(p('x','food','12,000원','단품','다른 자료 가격과 충돌')).unit,null);
assert.equal(B.price(p('x','food','12,000원부터')).open,true);
assert.equal(B.price({category:'outdoors'}).unit,null,'outdoors does not automatically mean free');
assert.equal(B.price({...food,priceInfo:{...food.priceInfo,source:'javascript:alert(1)'}}).unit,null);
assert.equal(B.price(free).unit,0);
const noMeals=B.routeItems({stops:[{placeId:'free'}],legs:[]},lookup);
assert.equal(B.estimate(noMeals,{...s}).status,'unknown','unselected food is not free');
assert.equal(B.estimate(noMeals,{...s,extraFood:0}).status,'within','explicit zero is valid');
assert.equal(B.estimate({...noMeals,unknownTransport:true},{...s,extraFood:0}).status,'unknown');
e=B.estimate(model,{...s,overrides:{'place:food':19000}});assert.equal(e.sum,41000,'override is party total, not multiplied again');
e=B.estimate(model,{...s,overrides:{'place:food':0}});assert.equal(e.sum,22000,'zero override is retained');
for(const value of ['-1','1.5','Infinity','1e3','100000001'])assert(Number.isNaN(B.amount(value)),value);
assert.equal(B.amount(''),null);assert.equal(B.amount('0'),0);assert.equal(B.amount('100000000'),100000000);
assert.equal(B.settings(null).people,1);assert.equal(B.settings({people:-1,total:-1}).total,null);
const complete=B.estimate(model,s), partial=B.estimate(noMeals,{...s});
assert.equal(B.choices([partial,complete])[0].index,1,'unknown cheap-looking routes cannot beat complete ones');
assert.equal(B.choices([]).length,0);
const twice=B.routeItems({rows:[{placeId:'museum'},{placeId:'museum'}]},lookup);
e=B.estimate(twice,{...s,extraFood:0,overrides:{'place:museum:visit:2':0}});
assert.equal(e.sum,6000,'second visit waiver must not erase first ticket');
assert.equal(B.estimate(model,{...s,extraTransport:8000}).sum,54000);
for(const file of ['places','gangneung-places','gyeongju-places']) {
  const all=JSON.parse(fs.readFileSync('public/'+file+'.json','utf8')).places;
  for(const place of all){const q=B.price(place);assert(q.unit===null||Number.isFinite(q.unit)&&q.unit>=0,place.id);}
}
const saved={id:'old',entries:{600:{placeId:'food',memo:'기존 메모'}},pending:[{entry:{placeId:'free'}}]};
const before=JSON.stringify(saved);B.settings(saved.budget);assert.equal(JSON.stringify(saved),before,'legacy data untouched');
const roundtrip=JSON.parse(JSON.stringify({...saved,budget:B.settings({...s,overrides:{'place:food':0}})}));
assert.equal(roundtrip.budget.overrides['place:food'],0);assert.equal(roundtrip.entries[600].memo,'기존 메모');
console.log('PASS budget: party units, zero/missing/lower-bound prices, transfer count, caps, overrides, candidate ranking, all cities, legacy data');
