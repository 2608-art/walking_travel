const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'public','gangneung-market-exterior-route.json'),'utf8'));
const qa=JSON.parse(fs.readFileSync(path.join(__dirname,'qa','gangneung-market-exterior-route-2026-10-07.json'),'utf8'));
const geojson=JSON.parse(fs.readFileSync(path.join(root,'public','gangneung-market-exterior-route.geojson'),'utf8'));
const gpx=fs.readFileSync(path.join(root,'public','gangneung-market-exterior-route.gpx'),'utf8');
assert.deepEqual(data,qa,'앱 경로와 검토본이 달라졌습니다.');
assert.equal(data.version,1);
assert.equal(data.themeId,'shops');
assert.equal(data.stops.map(x=>x.id).join(','),'g27,g8,g26,g1,g7');
assert.ok(!data.stops.some(x=>x.id==='g72'),'미확인 시장 내부 간선을 다시 넣지 마세요.');
assert.match(data.stops[3].routeLabel,/외곽 접근점/);
assert.match(data.source.label,/Valhalla/);
assert.equal(data.geometry.type,'LineString');
const coordinates=data.geometry.coordinates,indices=data.geometry.stopPointIndices;
assert.ok(coordinates.length>=30);
assert.equal(indices.length,data.stops.length);
assert.equal(indices[0],0);
assert.equal(indices.at(-1),coordinates.length-1);
assert.ok(indices.every((index,i)=>Number.isInteger(index)&&index>=0&&index<coordinates.length&&(i===0||index>indices[i-1])));
assert.ok(coordinates.every(p=>p.length===2&&p.every(Number.isFinite)));
assert.equal(data.legs.length,4);
assert.ok(data.legs.every((leg,i)=>leg.from===data.stops[i].id&&leg.to===data.stops[i+1].id&&leg.meters>0&&leg.meters<=1600));
assert.ok(Math.abs(data.meters-data.legs.reduce((sum,leg)=>sum+leg.meters,0))<=3);
assert.ok(data.limitations.some(s=>s.includes('시장 내부')));
assert.equal(geojson.type,'Feature');
assert.equal(geojson.geometry.type,'LineString');
assert.deepEqual(geojson.geometry.coordinates,coordinates);
assert.deepEqual(geojson.properties.stopIds,data.stops.map(stop=>stop.id));
const gpxPoints=[...gpx.matchAll(/<trkpt lat="([^"]+)" lon="([^"]+)"\/>/g)].map(match=>[Number(match[2]),Number(match[1])]);
assert.deepEqual(gpxPoints,coordinates);
assert.equal([...gpx.matchAll(/<wpt /g)].length,data.stops.length);
assert.match(gpx,/OSM\/Valhalla/);
assert.match(gpx,/GPX Studio 내보내기 파일 아님/);
const app=fs.readFileSync(path.join(root,'public','app.js'),'utf8');
assert.match(app,/if\(review\.theme==='shops'\).*id="view-market-short-route"/);
assert.match(app,/const routes=await buildMarketExteriorRoute\(state\.route\.date,'11:00'\)/);
assert.match(app,/state\.route\.review=null;state\.route\.reviewOptions=\[\];state\.route\.results=routes;state\.route\.baseResults=\[\.\.\.routes\];state\.route\.selected=0;showRouteResults\(\)/);
assert.match(app,/state\.resultMap\?\.remove\(\);state\.resultMap=null/);
console.log('PASS: 5개 외곽 정차점, 연속 보행망 4구간, 미확인 내부 길 제외, 시장 테마에서 기존 외곽 코스로 전환.');
